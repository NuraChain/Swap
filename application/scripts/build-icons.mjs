const require = createRequire(import.meta.url);
const iconsDir = join(dirname(require.resolve('lucide-static/package.json')), 'icons');

const symbols = ICONS.map((name) =>
{
    const svg = readFileSync(join(iconsDir, `${ name }.svg`), 'utf8');
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
    return `<symbol id="i-${ name }" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${ inner }</symbol>`;
});

// Filled glyphs need their own symbol shape: the outline defaults above would
// render a brand mark as a hairline outline of itself.
const brandSymbols = Object.entries(BRANDS).map(([name, d]) =>
    `<symbol id="i-${ name }" viewBox="0 0 24 24" fill="currentColor" stroke="none"><path d="${ d }"/></symbol>`);

const all = [...symbols, ...brandSymbols];
const sprite = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${ all.join('') }</svg>\n`;
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'icons.svg');
writeFileSync(out, sprite);
console.log(`icons.svg: ${ all.length } symbols (${ ICONS.length } outline, ${ brandSymbols.length } brand)`);
